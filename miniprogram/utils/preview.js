/**
 * =====================================================================
 * 图片预览工具（全站统一的「点开看大图」入口）
 * ---------------------------------------------------------------------
 * 为什么单独抽一个工具：
 *   头像散落在任务卡、用户 mini 卡片、我的发布 / 我的任务、个人中心、管理员后台…
 *   各页面各写一遍 wx.previewImage，很容易出现「有的头像能点开、有的点不动」的不一致；
 *   统一走这里，保证：
 *   1. 空地址（用户没上传头像）直接返回，不弹出空白预览；
 *   2. 传单个地址只预览这一张，传数组可左右滑动看多张（如送达照片）；
 *   3. 自动过滤空字符串，避免预览器里夹一张打不开的黑图。
 * 说明：预览不需要登录态；后端下发的带签名地址（?e=&s=）可直接预览。
 * =====================================================================
 */

/**
 * 预览一张或多张图片
 * @param {string|Array<string>} url 图片地址（相对路径 / 完整地址均可）
 * @returns {void}
 */
function previewImage(url) {
  const list = (Array.isArray(url) ? url : [url]).filter((item) => !!item);
  if (!list.length) return;
  wx.previewImage({ current: list[0], urls: list });
}

module.exports = { previewImage };
